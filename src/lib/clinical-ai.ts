/**
 * موتور هوشمند بالینی و ذهن‌آگاهی آراما (Arama Clinical Mind Engine)
 * الهام‌گرفته از استانداردهای درمانی CBT، ACT، ذهن‌آگاهی آرامیا و سوماتیک گراندینگ
 * تضمین می‌کند کاربر حتی در شرایط قطعی اینترنت بین‌الملل یا غیاب API Key،
 * همواره پاسخی عمیق، همدلانه، علمی و آرامش‌بخش دریافت کند.
 */

export interface ChatHistoryItem {
  role: string;
  content: string;
}

export function generateClinicalResponse(
  userText: string,
  history: ChatHistoryItem[] = [],
): string {
  const text = (userText || "").toLowerCase().trim();

  // 1. حمله اضطراب، پانیک، تپش قلب، تنگی نفس
  if (
    /پانیک|تپش قلب|تنگی نفس|نفسم بالا نمی|دارم میمیرم|می‌میرم|دستام میلرزه|لرزش دست|سکته|فشارم افتاده|گیج میره|خفگی|وحشت کردم|استرس شدید|دلشوره شدید|حالم خیلی بده/.test(
      text,
    )
  ) {
    return `صدات رو می‌شنوم و همین الان کنارتم. اول از همه می‌خوام خیالت رو راحت کنم: چیزی که داری تجربه می‌کنی یک «حمله اضطراب یا پانیک» است. این حالت بسیار ترسناک و سنگینه، اما **هیچ خطری برای قلبت یا جونت نداره** و بعد از چند دقیقه فروکش می‌کنه.

بیا همین لحظه این تمرین فیزیکی ۳ مرحله‌ای رو با هم انجام بدیم:
۱. **اتصال پاها:** کف هر دو پات رو محکم روی زمین بذار و حس کن زمین زیر پات چقدر محکمه.
۲. **تنفس کند:** یک نفس ملایم از بینی بکش (۴ ثانیه)... و خیلی آروم مثل فوت کردن یک شمع از بین لب‌هات بیرون بده (۶ ثانیه).
۳. **حواس پنج‌گانه:** به دوروبرت نگاه کن و ۳ تا شیء دوروبرت رو نام ببر.

من همین‌جام، اصلاً عجله نکن. الان ضربان قلبت و قفسه سینه‌ات در چه وضعیه؟`;
  }

  // 2. بی‌خوابی، نشخوار فکری شبانه، کلافگی در رختخواب
  if (
    /خوابم نمی|بی‌?خوابی|ساعت ۳|نصف شب|مغزم خاموش نمیشه|فکر و خیال|نشخوار فکری|نمی‌تونم بخوابم|خوابم نمی‌بره|کابوس|توی رختخواب|خوابم نمیاد/.test(
      text,
    )
  ) {
    return `می‌دونم چقدر کلافه‌کننده‌ست وقتی جسمت خسته‌ست ولی ذهنت مثل یک موتور پرسرعت مدام از فکری به فکر دیگه می‌پره.

اولین قاعدهٔ طلایی خواب: **«هیچ اصراری به خوابیدن نداشته باش»**؛ تلاش و تقلا برای خوابیدن، خودش سیستم عصبی رو بیدارتر نگه می‌داره.

همین الان توی رختخواب این کارها رو امتحان کن:
- بدنت رو کاملاً روی تشک رها کن و وزن تنت رو حس کن.
- دندان‌هات رو از هم باز کن، فک و زبونت رو کاملاً شل کن و شانه‌هات رو از گوش‌هات دور کن.
- اگر فکر مشخصی توی سرته، تصورش کن مثل ابریه که توی آسمون حرکت می‌کنه؛ لازم نیست باهاش بجنگی، فقط بذار از جلوی چشمت رد بشه.

می‌تونی از بخش صوت‌های آراما، قطعهٔ «فرکانس ۴۳۲ هرتز خواب عمیق» یا «صدای باران پشت پنجره» رو هم پخش کنی. دلت می‌خواد با هم یک تمرین تنفس خواب ۴-۷-۸ انجام بدیم؟`;
  }

  // 3. غم، شکست عاطفی، تنهایی، گریه و بغض
  if (
    /گریه|بغض|تنهایی|غمگین|دلم گرفته|شکست عشقی|کات کرد|جدایی|دلتنگ|هیچکس منو درک نمیکنه|تنها شدم|احساس پوچی|ناامیدم|بی‌پناه|دلم شکسته|دوستم نداره/.test(
      text,
    )
  ) {
    return `گاهی سنگینی بعضی غم‌ها اون‌قدر زیاده که آدم حس می‌کنه تنهایی داره بار یک کوه رو به دوش می‌کشه. اشکالی نداره اگر الان قوی نیستی؛ اشکالی نداره اگر چشم‌هات پر از اشکه یا دلت می‌خواد مدتی سکوت کنی. تمام این احساساتت اصیل و محترمن.

نمی‌خوام بهت بگم "غصه نخور" یا شعار بدم؛ چون الان زمان شنیده شدنِ دردته، نه انکار کردنش. 

دستت رو برای چند ثانیه بذار روی سینه‌ات؛ روی قلبت. گرمای دستت رو حس کن و به خودت یادآوری کن: «من توی این لحظهٔ سخت و دردناک، با خودم مهربانم و تنها نیستم.»

هر چقدر دلت می‌خواد برام بنویس؛ من اینجام و با تمام وجودم بهت گوش میدم. چی شد که این غم این‌قدر برات پررنگ شد؟`;
  }

  // 4. تنبلی، اهمال‌کاری، کمال‌گرایی، عذاب وجدان و بی انگیزگی
  if (
    /تنبلی|اهمال|عذاب وجدان|انگیزه ندارم|پشت گوش|کارام مونده|عقب افتادم|بی‌?مصرف|کمال‌?گرایی|شروع نمی‌تونم|حوصله ندارم|درس نمیخونم|بی هدف/.test(
      text,
    )
  ) {
    return `بذار یک نکتهٔ مهم رو برات روشن کنم: چیزی که بهش می‌گی تنبلی یا اهمال‌کاری، در واقع بی‌مسئولیتی نیست؛ شیوهٔ مغزت برای فرار از **«اضطرابِ نتیجه و فشارِ کمال‌گرایی»** است. وقتی یک کار در ذهنت بیش از حد بزرگ و سنگین به نظر می‌رسه، مغز وارد حالت انجماد (Freeze) میشه.

راه رهایی از این تله، حمله به کل کار نیست، بلکه تکنیک «ریزمرحلهٔ ۲ دقیقه‌ای» است:
قرار نیست کل اون پروژه یا درس رو امروز تموم کنی! فقط و فقط یک قدم فوق‌العاده کوچک که زیر دو دقیقه طول می‌کشه تعریف کن (مثلاً فقط باز کردن پوشه یا ورق زدن کتاب).

همین الان اون کاری که بابتش عذاب وجدان داری چیه؟ برام بنویس تا با هم خردش کنیم به کوچک‌ترین قدم ممکن.`;
  }

  // 5. خشم، عصبانیت شدید و پرخاشگری
  if (
    /عصبی|خشم|عصبانی|داد زدم|نفرت|کنترل خشم|داغونم از دستش|می‌خوام منفجر شم|پاره شدم|دیوونه شدم|کفرم در اومده/.test(
      text,
    )
  ) {
    return `خشم یک انرژی روانی بسیار داغ و شدیده. معمولاً خشم یک لایهٔ محافظه؛ زیر پوست خشم، احساساتی مثل «حس بی‌عدالتی، نادیده گرفته شدن، یا نقض حریم شخصی» پنهان شده.

قبل از اینکه کلمه‌ای بگی یا واکنشی نشون بدی که بعداً سنگینی‌اش روی دوش خودت بمونه:
۱. از اون محیط چند قدم فاصله بگیر.
۲. مچ دست‌هات یا صورتت رو با آب خنک بشور تا رفلکس آرام‌سازی بدنت فعال بشه.
۳. فک و عضلات شانت رو که الان سفت شدن، شل کن.

پشت این خشمی که الان داری تجربه می‌کنی، چه حق یا توقعی ازت پایمال شده بود؟`;
  }

  // 6. درخواست تمرین تنفس، مدیتیشن یا صوت
  if (
    /تنفس|مدیتیشن|صوت|آهنگ آرامش|موزیک آرامش|ریلکس|تکنیک|تمرین|اسکن بدن|جعبه‌ای|۴-۷-۸|چیکار کنم آروم شم/.test(
      text,
    )
  ) {
    return `عالیه، بدن و ذهنت دارن یک استراحت آگاهانه می‌خوان. بیا با هم تکنیک تنفس جعبه‌ای (Box Breathing) رو امتحان کنیم که سیستم عصبی سمپاتیک رو فوراً متعادل می‌کنه:

🟦 **۴ ثانیه دم عمیق از بینی** (هوا رو تا عمق شکم ببر)
⏸️ **۴ ثانیه حبس نفس** (بدون فشار در گلو)
🟩 **۴ ثانیه بازدم پیوسته و آرام از دهان**
⏸️ **۴ ثانیه مکث در خالی بودن ریه‌ها**

این چرخه رو ۴ بار تکرار کن. در کتابخانهٔ صوت‌های آراما هم می‌تونی همین الان قطعهٔ «راهنمای تنفس جعبه‌ای» یا «اسکن بدن ذهن‌آگاه» رو پخش کنی تا همراهت باشه. الان حست بعد از این چند نفس چیه؟`;
  }

  // 7. سلام و احوال‌پرسی اولیه
  if (/^سلام|^درود|^خوبی|^صبح بخیر|^عصر بخیر|^شب بخیر|^سلام آراما/.test(text)) {
    return `سلام دوست عزیزم، به آراما خوش اومدی 🌱
اینجا یک فضای کاملاً امن، خلوت و بدون هیچ قضاوتی برای توئه. می‌تونی هر احساسی که در این لحظه داری، از خستگی و دلشوره تا فکرها و دغدغه‌های روزمره‌ات رو با من در میون بذاری.

امروز چه هوایی در دلت جریان داره؟ حالت چطوره؟`;
  }

  // 8. تشکر و خداحافظی
  if (/مرسی|ممنون|خیلی کمکم کردی|دستت درد نکنه|خداحافظ|فعلا|آروم تر شدم|بهترم/.test(text)) {
    return `خوشحالم که تونستم کنارت باشم و قدمی در مسیر آرامشت برداری 🌱
یادت باشه این آرامش متعلق به شجاعت خودت برای مواجهه با احساساتته. هر زمان که احساس کردی ذهنت شلوغه یا نیاز به یک همراه شنوا داری، آراما همین‌جا منتظرته. مراقب خودت و قلبت باش.`;
  }

  // 9. پاسخ بالینی عمومی مبتنی بر تاریخچه (Socratic Reflective Listening)
  const isShort = text.length < 25;
  if (isShort) {
    return `می‌شنومَت و با دقت همراهتم. اگر راحت هستی، کمی بیشتر برام ازش بگو؛ در این لحظه کدام بخشش بیشتر از همه ذهنت رو درگیر کرده؟`;
  }

  const responses = [
    `همین که این موضوع رو کلمه‌به‌کلمه نوشتی و با من در میون گذاشتی، نشون میده که به آرامش روان خودت اهمیت میدی و شجاعت دیدن این احساسات رو داری.
وقتی به این ماجرا فکر می‌کنی، چه احساس یا فکری در پس‌زمینهٔ ذهنت بیشتر از همه پررنگ میشه؟`,

    `داستانت رو با تمام وجود شنیدم. گاهی این حجم از افکار مثل کلاف سردرگمی میشن که پیدا کردن سرنخش سخته. بیا به خودت فرصت بدیم؛ اگر قرار باشه فقط به یک قدم خیلی کوچک برای حس امنیتِ امروزت فکر کنی، اون قدم چی می‌تونه باشه؟`,

    `متوجهم و کنارت هستم. پذیرش این موقعیت کار ساده‌ای نیست و کاملاً حق داری که این احساسات رو تجربه کنی. اگر دوست داری، با هم بررسی کنیم ببینیم چه بخش‌هایی از این شرایط در کنترل توئه و کدوم بخش‌ها رو بهتره به آرامی رها کنی؟`,
  ];

  const index = Math.abs(text.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0)) % responses.length;
  return responses[index];
}
